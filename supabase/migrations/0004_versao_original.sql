-- acerto, despensa, histórico de valores, notificações) + catálogo de bancos.

-- ============ Acessos (login próprio com nível) ============
alter table public.membros
  add column id bigint generated by default as identity unique,
  add column login text,
  add column nome text,
  add column foto text,
  add column email_contato text,
  add column telefone text,
  add column nivel text not null default 'admin' check (nivel in ('admin','parceiro','lancador','leitor')),
  add column ativo boolean not null default true,
  add column onboarded boolean not null default false,
  add column avisos jsonb not null default '{}'::jsonb,
  add column criado_por uuid;
create unique index membros_login on public.membros (lower(login));

-- Cada pessoa logada só pode mudar o próprio perfil (nome, foto, contato, avisos).
-- Nível, login e ativação mudam só pelas funções de administrador abaixo.
revoke update on public.membros from authenticated, anon;
grant update (nome, foto, email_contato, telefone, onboarded, avisos) on public.membros to authenticated;
create policy "editar_meu_perfil" on public.membros for update to authenticated
  using (user_id = auth.uid()) with check (user_id = auth.uid());

