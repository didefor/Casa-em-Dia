-- ============ Cadastro de usuário: casa nova (admin) ou entrada numa casa (acesso criado pelo admin) ============
create or replace function public.ao_criar_usuario() returns trigger
language plpgsql security definer set search_path = public as $$
declare
  v_casa uuid;
  v_pessoa bigint;
  v_nome text := coalesce(nullif(new.raw_user_meta_data->>'nome',''), split_part(new.email,'@',1));
  v_login text := coalesce(nullif(new.raw_app_meta_data->>'login',''), split_part(new.email,'@',1));
  v_nivel text := coalesce(nullif(new.raw_app_meta_data->>'nivel',''), 'admin');
begin
  if (new.raw_app_meta_data ? 'casa_id') then
    v_casa := (new.raw_app_meta_data->>'casa_id')::uuid;
    v_pessoa := nullif(new.raw_app_meta_data->>'pessoa_id','')::bigint;
    insert into membros (casa_id, user_id, papel, login, nome, nivel, criado_por)
      values (v_casa, new.id, 'membro', v_login, v_nome, v_nivel, nullif(new.raw_app_meta_data->>'criado_por','')::uuid);
    if v_pessoa is not null then
      update pessoas set user_id = new.id, email = new.email where id = v_pessoa and casa_id = v_casa;
    else
      insert into pessoas (casa_id, name, user_id, email, color) values (v_casa, v_nome, new.id, new.email, '#f43f5e');
    end if;
  else
    insert into casas (nome) values (coalesce(nullif(new.raw_user_meta_data->>'casa',''), 'Casa de ' || v_nome))
      returning id into v_casa;
    insert into membros (casa_id, user_id, papel, login, nome, nivel)
      values (v_casa, new.id, 'dono', v_login, v_nome, 'admin');
    insert into ajustes (casa_id) values (v_casa);
    insert into pessoas (casa_id, name, user_id, email, color) values (v_casa, v_nome, new.id, new.email, '#2563eb');
    insert into bancos (casa_id, slug, bank, label, color, color2, fg, tier, aliases, source)
      select v_casa, slug, bank, label, color, color2, fg, tier, aliases, source from bancos_modelo;
  end if;
  return new;
end $$;
revoke execute on function public.ao_criar_usuario() from public, anon, authenticated;

-- ============ Funções de login (rodam no servidor do banco; ninguém vê senha de ninguém) ============
-- login sem "@" vira um e-mail interno (o Supabase entra por e-mail)
create or replace function public.email_do_login(p_login text) returns text
language sql immutable as $$
  select case when position('@' in p_login) > 0 then lower(trim(p_login))
              else lower(trim(p_login)) || '@casa-em-dia.local' end
$$;

-- cria o usuário no Auth do Supabase já confirmado (uso interno)
create or replace function public._criar_usuario(p_login text, p_senha text, p_nome text, p_app jsonb)
returns uuid language plpgsql security definer set search_path = public, extensions, auth as $$
declare v_id uuid := gen_random_uuid(); v_email text := public.email_do_login(p_login);
begin
  if coalesce(length(p_senha), 0) < 6 then raise exception 'A senha precisa ter pelo menos 6 caracteres'; end if;
  if trim(coalesce(p_login, '')) = '' then raise exception 'Informe o login'; end if;
  if exists (select 1 from auth.users where email = v_email) or exists (select 1 from public.membros where lower(login) = lower(trim(p_login))) then
    raise exception 'Esse login já existe';
  end if;
  insert into auth.users (instance_id, id, aud, role, email, encrypted_password, email_confirmed_at,
                          raw_app_meta_data, raw_user_meta_data, created_at, updated_at,
                          confirmation_token, recovery_token, email_change, email_change_token_new)
  values ('00000000-0000-0000-0000-000000000000', v_id, 'authenticated', 'authenticated', v_email,
          crypt(p_senha, gen_salt('bf')), now(),
          jsonb_build_object('provider','email','providers', jsonb_build_array('email'), 'login', trim(p_login)) || coalesce(p_app, '{}'::jsonb),
          jsonb_build_object('nome', coalesce(nullif(trim(p_nome),''), trim(p_login))), now(), now(), '', '', '', '');
  insert into auth.identities (id, user_id, provider_id, identity_data, provider, last_sign_in_at, created_at, updated_at)
  values (gen_random_uuid(), v_id, v_id::text,
          jsonb_build_object('sub', v_id::text, 'email', v_email, 'email_verified', true), 'email', now(), now(), now());
  return v_id;
end $$;
revoke execute on function public._criar_usuario(text, text, text, jsonb) from public, anon, authenticated;

-- sistema sem nenhum usuário? (mostra a tela de primeiro acesso)
create or replace function public.sistema_vazio() returns boolean
language sql stable security definer set search_path = public, auth as $$
  select not exists (select 1 from auth.users)
$$;
grant execute on function public.sistema_vazio() to anon, authenticated;

-- primeiro acesso: quem cria vira administrador
create or replace function public.criar_primeiro_acesso(p_login text, p_senha text) returns void
language plpgsql security definer set search_path = public, auth as $$
begin
  if exists (select 1 from auth.users) then raise exception 'O sistema já foi configurado'; end if;
  perform public._criar_usuario(p_login, p_senha, p_login, '{}'::jsonb);
end $$;
grant execute on function public.criar_primeiro_acesso(text, text) to anon, authenticated;

create or replace function public.sou_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from membros where user_id = auth.uid() and nivel = 'admin' and ativo)
$$;
grant execute on function public.sou_admin() to authenticated;

-- administrador cria um acesso: nos dados da casa (p_espaco='0') ou numa conta separada ('own')
create or replace function public.criar_acesso(p_login text, p_senha text, p_nome text, p_nivel text,
  p_pessoa bigint, p_espaco text, p_email text, p_telefone text) returns bigint
language plpgsql security definer set search_path = public, auth as $$
declare v_uid uuid; v_app jsonb; v_id bigint;
begin
  if not public.sou_admin() then raise exception 'Só o administrador cria acessos'; end if;
  if coalesce(p_nivel, '') not in ('admin','parceiro','lancador','leitor') then raise exception 'Nível inválido'; end if;
  if coalesce(p_espaco, 'own') = 'own' then
    v_app := jsonb_build_object('criado_por', auth.uid());
  else
    if p_pessoa is not null and not exists (select 1 from pessoas where id = p_pessoa and casa_id = public.casa_atual() and user_id is null) then
      raise exception 'Essa pessoa já tem acesso ou não é desta casa';
    end if;
    v_app := jsonb_build_object('casa_id', public.casa_atual(), 'pessoa_id', p_pessoa, 'nivel', p_nivel, 'criado_por', auth.uid());
  end if;
  v_uid := public._criar_usuario(p_login, p_senha, p_nome, v_app);
  update membros set nome = coalesce(nullif(trim(p_nome),''), login), email_contato = nullif(p_email,''), telefone = nullif(p_telefone,''),
         nivel = case when coalesce(p_espaco,'own') = 'own' then 'admin' else p_nivel end, criado_por = auth.uid()
   where user_id = v_uid returning id into v_id;
  return v_id;
end $$;
grant execute on function public.criar_acesso(text, text, text, text, bigint, text, text, text) to authenticated;

-- administrador altera um acesso da própria casa
create or replace function public.alterar_acesso(p_id bigint, p_nome text, p_login text, p_nivel text, p_senha text,
  p_ativo boolean, p_pessoa bigint, p_email text, p_telefone text) returns void
language plpgsql security definer set search_path = public, extensions, auth as $$
declare m membros;
begin
  if not public.sou_admin() then raise exception 'Só o administrador muda acessos'; end if;
  select * into m from membros where id = p_id and casa_id = public.casa_atual();
  if m.user_id is null then raise exception 'Acesso não encontrado'; end if;
  if m.user_id = auth.uid() and (p_ativo is false or coalesce(p_nivel, 'admin') <> 'admin') then
    raise exception 'Você não pode tirar o seu próprio acesso de administrador';
  end if;
  if p_nivel is not null and p_nivel not in ('admin','parceiro','lancador','leitor') then raise exception 'Nível inválido'; end if;
  if p_login is not null and lower(trim(p_login)) <> lower(coalesce(m.login, '')) then
    if exists (select 1 from membros where lower(login) = lower(trim(p_login)) and id <> p_id)
       or exists (select 1 from auth.users where email = public.email_do_login(p_login) and id <> m.user_id) then
      raise exception 'Esse login já existe';
    end if;
    update auth.users set email = public.email_do_login(p_login), updated_at = now() where id = m.user_id;
    update auth.identities set identity_data = identity_data || jsonb_build_object('email', public.email_do_login(p_login))
     where user_id = m.user_id and provider = 'email';
  end if;
  if coalesce(p_senha, '') <> '' then
    if length(p_senha) < 6 then raise exception 'A senha precisa ter pelo menos 6 caracteres'; end if;
    update auth.users set encrypted_password = crypt(p_senha, gen_salt('bf')), updated_at = now() where id = m.user_id;
  end if;
  update auth.users set banned_until = case when coalesce(p_ativo, true) then null else now() + interval '100 years' end where id = m.user_id;
  update membros set nome = coalesce(nullif(trim(p_nome),''), nome), login = coalesce(nullif(trim(p_login),''), login),
         nivel = coalesce(p_nivel, nivel), ativo = coalesce(p_ativo, true),
         email_contato = nullif(p_email,''), telefone = nullif(p_telefone,'')
   where id = p_id;
  if p_pessoa is not null and m.casa_id = public.casa_atual() then
    update pessoas set user_id = null, email = null where user_id = m.user_id and id <> p_pessoa;
    update pessoas set user_id = m.user_id where id = p_pessoa and casa_id = m.casa_id and (user_id is null or user_id = m.user_id);
  end if;
end $$;
grant execute on function public.alterar_acesso(bigint, text, text, text, text, boolean, bigint, text, text) to authenticated;

-- administrador exclui um acesso (a pessoa e os lançamentos dela continuam)
create or replace function public.excluir_acesso(p_id bigint) returns void
language plpgsql security definer set search_path = public, auth as $$
declare m membros;
begin
  if not public.sou_admin() then raise exception 'Só o administrador exclui acessos'; end if;
  select * into m from membros where id = p_id and casa_id = public.casa_atual();
  if m.user_id is null then raise exception 'Acesso não encontrado'; end if;
  if m.user_id = auth.uid() then raise exception 'Você não pode excluir o seu próprio acesso'; end if;
  update pessoas set email = null where user_id = m.user_id;
  delete from auth.users where id = m.user_id;
end $$;
grant execute on function public.excluir_acesso(bigint) to authenticated;

-- trocar a própria senha conferindo a atual
create or replace function public.trocar_minha_senha(p_atual text, p_nova text) returns void
language plpgsql security definer set search_path = public, extensions, auth as $$
begin
  if coalesce(length(p_nova), 0) < 6 then raise exception 'A senha nova precisa ter pelo menos 6 caracteres'; end if;
  if not exists (select 1 from auth.users where id = auth.uid() and encrypted_password = crypt(coalesce(p_atual,''), encrypted_password)) then
    raise exception 'Senha atual incorreta';
  end if;
  update auth.users set encrypted_password = crypt(p_nova, gen_salt('bf')), updated_at = now() where id = auth.uid();
end $$;
grant execute on function public.trocar_minha_senha(text, text) to authenticated;

-- ajustar_sequencias passa a cobrir as tabelas novas
create or replace function public.ajustar_sequencias() returns void
language plpgsql security definer set search_path = public as $$
declare t text;
begin
  foreach t in array array[
    'pessoas','bancos','bens','contas_bancarias','cartoes','contas_fixas','compras_cartao',
    'caixinhas','movimentos_caixinha','emprestimos','pagamentos_emprestimo','movimentos_conta',
    'recorrentes','assinaturas','receitas','lancamentos','recebimentos','produtos_despensa',
    'compras_despensa','projetos','pagamentos','ajustes_ocorrencia','acertos','receitas_valores',
    'valores_bem','movimentos_despensa','notificacoes'
  ] loop
    execute format('select setval(pg_get_serial_sequence(%L,''id''), coalesce((select max(id) from public.%I),0)+1, false)',
                   'public.'||t, t);
  end loop;
end $$;
revoke all on function public.ajustar_sequencias() from public, anon, authenticated;
grant execute on function public.ajustar_sequencias() to service_role;
