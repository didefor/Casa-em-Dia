  add column ref_month text,
  add column bill_id bigint references public.contas_fixas(id) on delete set null;

-- pagamentos: os tipos passam a ser os da interface (bill, card, loan, saving, subscription, reminder)
alter table public.pagamentos drop constraint pagamentos_item_type_check;
alter table public.pagamentos add constraint pagamentos_item_type_check
  check (item_type in ('bill','card','loan','saving','subscription','reminder'));

-- valor ajustado / pulado só numa ocorrência (conta fixa no mês, ou pagamento recorrente na data)
create table public.ajustes_ocorrencia (
  id bigint generated by default as identity primary key,
  casa_id uuid not null references public.casas(id) on delete cascade default public.casa_atual(),
  item_type text not null check (item_type in ('bill','reminder')),
  item_id bigint not null,
  ref text not null,           -- AAAA-MM (conta) ou AAAA-MM-DD (recorrente)
  amount numeric, note text, skip boolean not null default false,
  unique (casa_id, item_type, item_id, ref)
);

-- acerto da casa marcado como feito
create table public.acertos (
  id bigint generated by default as identity primary key,
  casa_id uuid not null references public.casas(id) on delete cascade default public.casa_atual(),
  month text not null, done boolean not null default true, amount numeric,
  unique (casa_id, month)
);

-- reajustes de receita (valor vale a partir de um mês)
create table public.receitas_valores (
  id bigint generated by default as identity primary key,
  casa_id uuid not null references public.casas(id) on delete cascade default public.casa_atual(),
  income_id bigint not null references public.receitas(id) on delete cascade,
  from_month text not null, amount numeric not null
);

-- histórico de valor de mercado dos bens
create table public.valores_bem (
  id bigint generated by default as identity primary key,
  casa_id uuid not null references public.casas(id) on delete cascade default public.casa_atual(),
  asset_id bigint not null references public.bens(id) on delete cascade,
  date date not null default current_date, value numeric not null, source text
);

-- despensa: cada compra, uso ou contagem
create table public.movimentos_despensa (
  id bigint generated by default as identity primary key,
  casa_id uuid not null references public.casas(id) on delete cascade default public.casa_atual(),
  item_id bigint not null references public.produtos_despensa(id) on delete cascade,
  date date not null default current_date,
  kind text not null check (kind in ('compra','uso','ajuste')),
  qty numeric not null, prev_qty numeric, unit_price numeric, total numeric, store text,
  transaction_id bigint references public.lancamentos(id) on delete set null,
  criado_em timestamptz not null default now()
);

-- sininho
create table public.notificacoes (
  id bigint generated by default as identity primary key,
  casa_id uuid not null references public.casas(id) on delete cascade default public.casa_atual(),
  user_id uuid references auth.users(id) on delete cascade,
  kind text, title text not null, body text, url text, action jsonb, tag text,
  read boolean not null default false,
  created_at timestamptz not null default now()
);

do $$
declare t text;
begin
  foreach t in array array['ajustes_ocorrencia','acertos','receitas_valores','valores_bem','movimentos_despensa','notificacoes'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('create policy "casa_%s" on public.%I for all to authenticated
                    using (casa_id = public.casa_atual()) with check (casa_id = public.casa_atual())', t, t);
  end loop;
end $$;

