-- Casa em Dia (versão nuvem) — estrutura do banco
-- Rodar uma vez no projeto Supabase (SQL Editor ou API).
-- Nomes das tabelas = "tipos" do Casa em Dia original; colunas iguais, para a migração ser direta.

create extension if not exists pgcrypto;

-- ============ CASA (household) e membros ============
create table public.casas (
  id uuid primary key default gen_random_uuid(),
  nome text not null default 'Minha casa',
  criado_em timestamptz not null default now()
);

create table public.membros (
  casa_id uuid not null references public.casas(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  papel text not null default 'membro' check (papel in ('dono','membro')),
  criado_em timestamptz not null default now(),
  primary key (casa_id, user_id),
  unique (user_id) -- cada login pertence a uma casa só
);

-- casa do usuário logado (usado como valor padrão e nas regras de acesso)
create or replace function public.casa_atual() returns uuid
language sql stable security definer set search_path = public as $$
  select casa_id from public.membros where user_id = auth.uid() limit 1
$$;

create table public.ajustes (
  casa_id uuid primary key references public.casas(id) on delete cascade default public.casa_atual(),
  daily_budget numeric not null default 0,
  housing_ref numeric not null default 30,
  split_mode text not null default 'proporcional' check (split_mode in ('proporcional','igual')),
  reserve_goal numeric not null default 0
);

-- ============ CADASTROS ============
create table public.pessoas (
  id bigint generated by default as identity primary key,
  casa_id uuid not null references public.casas(id) on delete cascade default public.casa_atual(),
  name text not null,
  color text,
  salary numeric default 0,
  user_id uuid references auth.users(id) on delete set null,  -- login ligado a esta pessoa (opcional)
  email text                                                   -- e-mail do acesso (só para exibir)
);

create table public.bancos (
  id bigint generated by default as identity primary key,
  casa_id uuid not null references public.casas(id) on delete cascade default public.casa_atual(),
  slug text, bank text, label text, color text, color2 text, fg text, tier text, aliases text, source text
);

create table public.bens (
  id bigint generated by default as identity primary key,
  casa_id uuid not null references public.casas(id) on delete cascade default public.casa_atual(),
  name text not null, kind text, brand text, model text, year text, plate text, address text,
  purchase_date date, purchase_price numeric, market_value numeric, value_date date,
  fipe_type text, fipe_code text, fipe_year text,
  owner_id bigint references public.pessoas(id) on delete set null,
  notes text, active boolean not null default true, paid_before numeric, area numeric
);

create table public.contas_bancarias (
  id bigint generated by default as identity primary key,
  casa_id uuid not null references public.casas(id) on delete cascade default public.casa_atual(),
  name text not null, bank text, preset text,
  owner_id bigint references public.pessoas(id) on delete set null,
  opening_balance numeric not null default 0, opening_date date not null default current_date,
  salary_day int, color text, active boolean not null default true, notes text
);

create table public.cartoes (
  id bigint generated by default as identity primary key,
  casa_id uuid not null references public.casas(id) on delete cascade default public.casa_atual(),
  name text not null, bank text, color text, limit_total numeric default 0,
  closing_day int, due_day int,
  owner_id bigint references public.pessoas(id) on delete set null,
  preset text, image text, network text,
  account_id bigint references public.contas_bancarias(id) on delete set null,
  auto_debit boolean not null default false, kind text
);

create table public.contas_fixas (
  id bigint generated by default as identity primary key,
  casa_id uuid not null references public.casas(id) on delete cascade default public.casa_atual(),
  name text not null, amount numeric not null default 0, due_day int,
  kind text default 'casa',  -- casa (dividida) | pessoal
  owner_id bigint references public.pessoas(id) on delete set null,
  is_housing boolean not null default false, is_reserve boolean not null default false,
  start_month text check (start_month ~ '^\d{4}-\d{2}$'), end_month text check (end_month ~ '^\d{4}-\d{2}$'),
  active boolean not null default true, notes text,
  account_id bigint references public.contas_bancarias(id) on delete set null,
  asset_id bigint references public.bens(id) on delete set null
);

create table public.compras_cartao (
  id bigint generated by default as identity primary key,
  casa_id uuid not null references public.casas(id) on delete cascade default public.casa_atual(),
  card_id bigint not null references public.cartoes(id) on delete cascade,
  description text, total numeric not null, installments int not null default 1,
  first_month text not null check (first_month ~ '^\d{4}-\d{2}$'),
  asset_id bigint references public.bens(id) on delete set null,
  date date default current_date, category text
);

create table public.caixinhas (
  id bigint generated by default as identity primary key,
  casa_id uuid not null references public.casas(id) on delete cascade default public.casa_atual(),
  name text not null, account text, goal numeric, target_month text, monthly numeric, day int,
  icon text, color text, owner_id bigint references public.pessoas(id) on delete set null,
  active boolean not null default true,
  from_account_id bigint references public.contas_bancarias(id) on delete set null
);

create table public.movimentos_caixinha (
  id bigint generated by default as identity primary key,
  casa_id uuid not null references public.casas(id) on delete cascade default public.casa_atual(),
  date date not null default current_date, amount numeric not null, note text,
  savings_id bigint not null references public.caixinhas(id) on delete cascade
);

create table public.emprestimos (
  id bigint generated by default as identity primary key,
  casa_id uuid not null references public.casas(id) on delete cascade default public.casa_atual(),
  name text not null, lender text, principal numeric, installment numeric, installments int,
  first_date date, owner_id bigint references public.pessoas(id) on delete set null,
  notes text, active boolean not null default true,
  account_id bigint references public.contas_bancarias(id) on delete set null,
  asset_id bigint references public.bens(id) on delete set null,
  bank_balance numeric, bank_balance_date date
);

create table public.pagamentos_emprestimo (
  id bigint generated by default as identity primary key,
  casa_id uuid not null references public.casas(id) on delete cascade default public.casa_atual(),
  loan_id bigint not null references public.emprestimos(id) on delete cascade,
  date date not null default current_date, amount numeric not null, installment_no int,
  kind text default 'parcela', covers int, note text
);

create table public.movimentos_conta (
  id bigint generated by default as identity primary key,
  casa_id uuid not null references public.casas(id) on delete cascade default public.casa_atual(),
  account_id bigint not null references public.contas_bancarias(id) on delete cascade,
  date date not null default current_date, amount numeric not null, kind text, note text
);

create table public.recorrentes (
  id bigint generated by default as identity primary key,
  casa_id uuid not null references public.casas(id) on delete cascade default public.casa_atual(),
  name text not null, amount numeric, frequency text, weekday int, day int, time text,
  start_date date, end_date date,
  account_id bigint references public.contas_bancarias(id) on delete set null,
  owner_id bigint references public.pessoas(id) on delete set null,
  category text, active boolean not null default true, notes text,
  asset_id bigint references public.bens(id) on delete set null
);

create table public.assinaturas (
  id bigint generated by default as identity primary key,
  casa_id uuid not null references public.casas(id) on delete cascade default public.casa_atual(),
  name text not null, platform text, plan text, category text, amount numeric not null default 0,
  currency text default 'BRL', amount_original numeric, cycle text default 'mensal', day int,
  method text, card_id bigint references public.cartoes(id) on delete set null,
  account_id bigint references public.contas_bancarias(id) on delete set null,
  owner_id bigint references public.pessoas(id) on delete set null,
  start_month text, end_month text, active boolean not null default true, url text, notes text
);

create table public.receitas (
  id bigint generated by default as identity primary key,
  casa_id uuid not null references public.casas(id) on delete cascade default public.casa_atual(),
  name text not null, payer text, kind text,
  owner_id bigint references public.pessoas(id) on delete set null,
  account_id bigint references public.contas_bancarias(id) on delete set null,
  amount numeric not null default 0, amount_type text default 'fixo', cycle text default 'mensal',
  day int, installments_per_cycle int default 1, start_month text, end_month text, total_months int,
  renewal text, category text, active boolean not null default true, notes text
);

create table public.lancamentos (
  id bigint generated by default as identity primary key,
  casa_id uuid not null references public.casas(id) on delete cascade default public.casa_atual(),
  date date not null default current_date, description text, amount numeric not null,
  type text not null check (type in ('entrada','saida')),
  category text,
  person_id bigint references public.pessoas(id) on delete set null,
  account_id bigint references public.contas_bancarias(id) on delete set null, -- vazio = dinheiro
  asset_id bigint references public.bens(id) on delete set null,
  kind text not null default 'normal', -- normal | transferencia | caixinha | pagamento_fatura | pagamento
  ext_id text, reminder_id bigint,
  criado_em timestamptz not null default now()
);

create table public.recebimentos (
  id bigint generated by default as identity primary key,
  casa_id uuid not null references public.casas(id) on delete cascade default public.casa_atual(),
  income_id bigint not null references public.receitas(id) on delete cascade,
  ref_month text not null, date date not null default current_date, amount numeric not null,
  account_id bigint references public.contas_bancarias(id) on delete set null, note text,
  lancamento_id bigint references public.lancamentos(id) on delete set null
);

create table public.produtos_despensa (
  id bigint generated by default as identity primary key,
  casa_id uuid not null references public.casas(id) on delete cascade default public.casa_atual(),
  name text not null, category text, unit text default 'un', qty numeric not null default 0,
  min_qty numeric not null default 0, notes text, active boolean not null default true
);

create table public.compras_despensa ( -- histórico de preços
  id bigint generated by default as identity primary key,
  casa_id uuid not null references public.casas(id) on delete cascade default public.casa_atual(),
  produto_id bigint not null references public.produtos_despensa(id) on delete cascade,
  date date not null default current_date, qty numeric not null, unit_price numeric, store text
);

create table public.projetos (
  id bigint generated by default as identity primary key,
  casa_id uuid not null references public.casas(id) on delete cascade default public.casa_atual(),
  name text not null, description text, monthly_amount numeric, status text default 'ativo',
  budget_total numeric, start_month text, end_month text,
  asset_id bigint references public.bens(id) on delete set null
);

-- marca "pago" dos itens de A pagar (conta fixa, fatura, parcela, assinatura, caixinha)
create table public.pagamentos (
  id bigint generated by default as identity primary key,
  casa_id uuid not null references public.casas(id) on delete cascade default public.casa_atual(),
  item_type text not null check (item_type in ('conta_fixa','fatura','emprestimo','assinatura','caixinha')),
  item_id bigint not null, ref_month text not null, amount numeric not null,
  date date not null default current_date,
  account_id bigint references public.contas_bancarias(id) on delete set null,
  lancamento_id bigint references public.lancamentos(id) on delete set null,
  extra_tabela text, extra_id bigint, -- registro criado junto (pagamento de empréstimo / movimento de caixinha)
  unique (casa_id, item_type, item_id, ref_month)
);

create index on public.lancamentos (casa_id, date);
create index on public.compras_cartao (casa_id, card_id);
create index on public.pagamentos (casa_id, ref_month);
create index on public.recebimentos (casa_id, ref_month);
