-- Casa em Dia — WhatsApp: cada usuário liga o próprio número, e o agente (OpenClaw) age por ele.
-- Como funciona:
--  1. Em Meu perfil a pessoa informa o número. O site cria uma chave de IA só para o WhatsApp,
--     guarda essa chave cifrada (a chave mestra fica só na Vercel) e mostra um código de 6 números.
--  2. A pessoa manda o código para o WhatsApp do agente. O agente chama "vincular" e o número fica confirmado.
--  3. A cada mensagem, o agente informa o número de quem mandou; o site acha a chave daquele número e age como a pessoa.

create table public.whatsapp_vinculos (
  id bigint generated by default as identity primary key,
  casa_id uuid not null references public.casas(id) on delete cascade default public.casa_atual(),
  user_id uuid not null unique references auth.users(id) on delete cascade default auth.uid(),
  telefone text not null unique,
  codigo_hash text, codigo_expira timestamptz, tentativas int not null default 0,
  confirmado boolean not null default false,
  chave_cifrada text not null, token_id bigint,
  criado_em timestamptz not null default now(), confirmado_em timestamptz, ultimo_uso timestamptz
);
alter table public.whatsapp_vinculos enable row level security;
create policy "meu_whatsapp" on public.whatsapp_vinculos for select to authenticated using (user_id = auth.uid());
revoke insert, update, delete on public.whatsapp_vinculos from anon, authenticated;

-- segredo do agente (só o hash fica aqui)
create table public.segredos (nome text primary key, hash text not null);
alter table public.segredos enable row level security;
revoke all on public.segredos from anon, authenticated;

create or replace function public._agente_ok(p_segredo text) returns boolean
language sql stable security definer set search_path = public, extensions as $$
  select exists (select 1 from segredos where nome = 'agente_whatsapp' and hash = encode(digest(coalesce(p_segredo, ''), 'sha256'), 'hex'))
$$;
revoke execute on function public._agente_ok(text) from public, anon, authenticated;

-- variações do número no Brasil (com e sem o 9 do celular)
create or replace function public._telefones(p text) returns text[]
language sql immutable as $$
  select case
    when p ~ '^55\d{2}9\d{8}$' then array[p, substr(p, 1, 4) || substr(p, 6)]
    when p ~ '^55\d{10}$' then array[p, substr(p, 1, 4) || '9' || substr(p, 5)]
    else array[p] end
$$;

-- 1. quem está logado pede para ligar um número (o site já criou a chave de IA e cifrou)
create or replace function public.whatsapp_iniciar(p_telefone text, p_codigo text, p_cifrada text, p_token bigint) returns void
language plpgsql security definer set search_path = public, extensions, auth as $$
declare v_antigo whatsapp_vinculos;
begin
  if auth.uid() is null or exists (select 1 from membros where user_id = auth.uid() and token) then raise exception 'Entre com a sua conta'; end if;
  if p_telefone !~ '^\d{12,13}$' then raise exception 'Número inválido. Use DDD e número, ex.: (11) 91234-5678'; end if;
  if exists (select 1 from whatsapp_vinculos where telefone = any(public._telefones(p_telefone)) and confirmado and user_id <> auth.uid()) then
    raise exception 'Esse número já está ligado a outra conta';
  end if;
  select * into v_antigo from whatsapp_vinculos where user_id = auth.uid();
  if v_antigo.token_id is not null and v_antigo.token_id <> p_token then
    delete from auth.users where id = (select user_id from membros where id = v_antigo.token_id and token);
  end if;
  delete from whatsapp_vinculos where user_id = auth.uid() or (telefone = any(public._telefones(p_telefone)) and not confirmado);
  insert into whatsapp_vinculos (casa_id, user_id, telefone, codigo_hash, codigo_expira, chave_cifrada, token_id)
    values (public.casa_atual(), auth.uid(), p_telefone, encode(digest(p_codigo, 'sha256'), 'hex'), now() + interval '30 minutes', p_cifrada, p_token);
end $$;
grant execute on function public.whatsapp_iniciar(text, text, text, bigint) to authenticated;

-- desligar o WhatsApp (apaga a chave junto)
create or replace function public.whatsapp_desligar() returns void
language plpgsql security definer set search_path = public, auth as $$
declare v whatsapp_vinculos;
begin
  select * into v from whatsapp_vinculos where user_id = auth.uid();
  if v.id is null then return; end if;
  delete from whatsapp_vinculos where id = v.id;
  delete from auth.users where id = (select user_id from membros where id = v.token_id and token);
end $$;
grant execute on function public.whatsapp_desligar() to authenticated;

-- 2. o agente confirma o código que a pessoa mandou do próprio WhatsApp
create or replace function public.whatsapp_confirmar(p_segredo text, p_telefone text, p_codigo text) returns text
language plpgsql security definer set search_path = public, extensions as $$
declare v whatsapp_vinculos; v_nome text;
begin
  if not public._agente_ok(p_segredo) then raise exception 'Agente não autorizado'; end if;
  select * into v from whatsapp_vinculos where telefone = any(public._telefones(p_telefone)) and not confirmado order by criado_em desc limit 1;
  if v.id is null then return 'nenhum'; end if;
  if v.tentativas >= 5 or v.codigo_expira < now() then return 'expirado'; end if;
  if v.codigo_hash <> encode(digest(regexp_replace(coalesce(p_codigo, ''), '\D', '', 'g'), 'sha256'), 'hex') then
    update whatsapp_vinculos set tentativas = tentativas + 1 where id = v.id;
    return 'errado';
  end if;
  update whatsapp_vinculos set confirmado = true, confirmado_em = now(), codigo_hash = null, telefone = p_telefone where id = v.id;
  select coalesce(nome, login) into v_nome from membros where user_id = v.user_id;
  return 'ok:' || coalesce(v_nome, '');
end $$;
grant execute on function public.whatsapp_confirmar(text, text, text) to anon, authenticated;

-- 3. o agente pede a chave (cifrada) de um número confirmado
create or replace function public.whatsapp_chave(p_segredo text, p_telefone text) returns text
language plpgsql security definer set search_path = public, extensions as $$
declare v whatsapp_vinculos;
begin
  if not public._agente_ok(p_segredo) then raise exception 'Agente não autorizado'; end if;
  select * into v from whatsapp_vinculos where telefone = any(public._telefones(p_telefone)) and confirmado limit 1;
  if v.id is null then return null; end if;
  update whatsapp_vinculos set ultimo_uso = now() where id = v.id;
  return v.chave_cifrada;
end $$;
grant execute on function public.whatsapp_chave(text, text) to anon, authenticated;
